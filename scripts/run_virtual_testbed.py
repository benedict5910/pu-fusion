"""Run the virtual testbed scenario suite (OB4) and write the evidence.

  python scripts/run_virtual_testbed.py --out results/final/ob4_testbed
Writes testbed.json (per-scenario summary + checks), traces.csv, events.csv, health.db and one
HTML report + CSV history per scenario (generated by the same HealthStore the dashboard uses).
Exit code 1 if any check fails.
"""
import argparse
import csv
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from pufusion import testbed as T  # noqa: E402
from pufusion.store import HealthStore  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "results/final/ob4_testbed"))
    ap.add_argument("--gearbox-data", default="")
    a = ap.parse_args()
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    (out / "reports").mkdir(exist_ok=True)
    db = out / "health.db"
    if db.exists():
        db.unlink()
    store = HealthStore(db)
    ctx = T.Context(a.gearbox_data or None)
    results, traces, skipped, t0 = [], [], [], time.time()
    for scn in T.default_scenarios():
        if scn.subsystem == "gearbox" and (ctx.gearbox is None or scn.recording not in ctx.gearbox_recs):
            skipped.append(scn.name)
            continue
        run = T.run_scenario(scn, ctx, store)
        s = T.summarize(scn, run, T.check(scn, run, store))
        results.append(s)
        traces += [{"scenario": scn.name, **{k: (json.dumps(v) if isinstance(v, dict) else v) for k, v in w.items()}}
                   for w in run["trace"]]
        store.export_html(out / "reports" / f"report_{run['asset']}.html", run["asset"])
        store.export_csv(out / "reports" / f"history_{run['asset']}.csv", run["asset"])
        fails = [c["check"] for c in s["checks"] if not c["passed"]]
        seg = " | ".join(f"{g['fault']}: {g['end_state']} ({g['diagnosis_coverage']:.0%})" for g in s["segments"])
        print(f"{'PASS' if s['passed'] else 'FAIL'} {scn.name:30s} {seg}" + (f"  FAILED: {fails}" if fails else ""), flush=True)
    events = store.events()
    with open(out / "events.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(events[0])); w.writeheader(); w.writerows(events)
    with open(out / "traces.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(traces[0])); w.writeheader(); w.writerows(traces)
    n_checks = sum(len(s["checks"]) for s in results)
    n_pass = sum(c["passed"] for s in results for c in s["checks"])
    summary = {"scenarios": len(results), "scenarios_passed": sum(s["passed"] for s in results),
               "checks": n_checks, "checks_passed": n_pass, "windows": len(traces), "events_logged": len(events),
               "skipped_no_data": skipped,
               "data": "real held-out recordings (Paderborn K004/KA22/KI18; MCC5-THU 1000 rpm 10 Nm); synthetic sensor faults",
               "results": results}
    (out / "testbed.json").write_text(json.dumps(summary, indent=2))
    store.close()
    print(f"\n{summary['scenarios_passed']}/{summary['scenarios']} scenarios, {n_pass}/{n_checks} checks passed; "
          f"{len(traces)} windows, {len(events)} events logged; skipped {skipped}  ({time.time() - t0:.0f}s)")
    return 0 if n_pass == n_checks else 1


if __name__ == "__main__":
    sys.exit(main())
