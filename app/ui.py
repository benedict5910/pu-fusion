def grid(cards, min_px: int = 200) -> str:
    """Responsive card grid: as many columns as fit, never narrower than `min_px`."""
    return (f"<div class='ivhm-grid' style='grid-template-columns:repeat(auto-fit,minmax({int(min_px)}px,1fr))'>"
            + "".join(cards) + "</div>")


PIPELINE = [("Sensors", "vibration + motor current"), ("Signal quality", "label-free reliability (OB2)"),
            ("Diagnosis", "reliability-gated fusion (OB1)"), ("Health layer", "states, rules, advice (OB3)"),
            ("Operator", "dashboard, log, reports")]


def pipeline_html() -> str:
    """Monitoring pipeline as numbered, wrapping HTML boxes (stays readable at any width)."""
    parts = [f"<div class='nd'><b><i>{k + 1}</i>{esc(t)}</b><div>{esc(s)}</div></div>"
             for k, (t, s) in enumerate(PIPELINE)]
    return "<div class='ivhm-flow'>" + "".join(parts) + "</div>"


def demo_header(idx, total: int) -> str:
    pips = "".join(f"<span class='ivhm-pip{' on' if idx == i else (' done' if idx is not None and i < idx else '')}'>"
                   f"{i + 1}</span>" for i in range(total))
    return pips


