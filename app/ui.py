def esc(s) -> str:
    return html.escape(str(s))


def fmt_ts(ts: float | None, with_date: bool = True) -> str:
    if ts is None:
        return "-"
    return time.strftime("%d %b %Y, %H:%M:%S" if with_date else "%H:%M:%S", time.localtime(ts))


def hero(title: str, subtitle: str, right_html: str = "") -> str:
    return (f"<div class='ivhm-hero'><div><div class='t'>{title}</div><div class='s'>{esc(subtitle)}</div></div>"
            f"<div>{right_html}</div></div>")


def badge(text: str, color: str) -> str:
    return (f"<span class='ivhm-badge' style='color:{color};border-color:{color}55;background:{color}1a'>"
            f"{esc(text)}</span>")


def source_banner(kind: str, extra: str = "") -> str:
    s = SOURCES[kind]
    return (f"<div class='ivhm-source' style='border-left-color:{s['color']}'>{badge(s['tag'], s['color'])}"
            f"<div><div class='tt'>{esc(s['title'])}</div><div class='dd'>{esc(s['detail'])}"
            f"{(' ' + esc(extra)) if extra else ''}</div></div></div>")


def card(title: str, body_html: str) -> str:
    return f"<div class='ivhm-card'><div class='ch'>{esc(title)}</div>{body_html}</div>"


def kpi(value: str, unit: str = "", sub: str = "") -> str:
    return (f"<div class='ivhm-kpi'>{esc(value)} <small>{esc(unit)}</small></div>"
            + (f"<div class='ivhm-sub'>{sub}</div>" if sub else ""))


def state_banner(state: str, rule: str, meta: str = "") -> str:
    c = STATE_COLOR.get(state, MUTED)
    return (f"<div class='ivhm-state' style='background:{c}14;border-color:{c}66'>"
            f"<span class='ivhm-dot' style='color:{c};background:{c}'></span>"
            f"<div><div class='st' style='color:{c}'>{esc(state.replace('_', ' '))}</div>"
            f"<div class='rule'>{esc(STATE_TEXT.get(state, ''))} &middot; <span style='color:{MUTED}'>rule: "
            f"{esc(rule)}</span></div>" + (f"<div class='meta'>{esc(meta)}</div>" if meta else "") + "</div></div>")


def bar(label: str, value: float | None, color: str = ACCENT, fmt: str = "{:.2f}") -> str:
    v = 0.0 if value is None else max(0.0, min(1.0, float(value)))
    txt = "n/a" if value is None else fmt.format(value)
    return (f"<div class='ivhm-bar'><div class='lab'><span>{esc(label)}</span><span>{txt}</span></div>"
            f"<div class='trk'><div class='fil' style='width:{v * 100:.1f}%;background:{color}'></div></div></div>")


def alert(kind: str, title: str, body: str) -> str:
    col = {"info": ACCENT2, "warn": STATE_COLOR["WARNING"], "danger": STATE_COLOR["INSPECT"],
           "ok": STATE_COLOR["NORMAL"], "purple": STATE_COLOR["SENSOR_FAULT"]}[kind]
    return (f"<div class='ivhm-alert' style='border-color:{col}66;background:{col}12'>"
            f"<b style='color:{col}'>{esc(title)}</b><br><span>{body}</span></div>")


def ulist(items) -> str:
    return "<ul class='ivhm-list'>" + "".join(f"<li>{esc(i)}</li>" for i in items) + "</ul>"


def event_table(events, limit: int = 60) -> str:
    """State-change audit trail as a wrapping HTML table (newest last, at most `limit` rows)."""
    ev = list(events)[-limit:]
    rows = "".join(
        f"<tr><td class='t'>{fmt_ts(e['ts'])}</td><td style='white-space:nowrap'>"
        f"{badge(e['from_state'].replace('_', ' '), STATE_COLOR.get(e['from_state'], MUTED))} &#8594; "
        f"{badge(e['to_state'].replace('_', ' '), STATE_COLOR.get(e['to_state'], MUTED))}</td>"
        f"<td>{esc(e['rule'])}</td></tr>" for e in ev)
    return ("<table class='ivhm-table'><thead><tr><th>Time</th><th>Transition</th><th>Rule that fired</th></tr>"
            f"</thead><tbody>{rows}</tbody></table>")


def sensor_card_html(name: str, status: str, score: float, reasons) -> str:
    c = REL_COLOR.get(status, MUTED)
    why = ", ".join(reasons) if reasons else "all quality indicators within the learned clean range"
    return (f"<div style='display:flex;justify-content:space-between;align-items:center'>"
            f"<span style='font-weight:600;color:{TEXT}'>{esc(name)}</span>{badge(status.upper(), c)}</div>"
            + bar("reliability score", score, c) + f"<div class='ivhm-sub'>{esc(why)}</div>")


